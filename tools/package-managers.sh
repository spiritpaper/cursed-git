#!/bin/sh
# Writes the Homebrew formula and the Scoop manifest for a release, from its checksums.
#
#   tools/package-managers.sh v0.2.0 dist/checksums.txt out/
#
# out/cg.rb   goes to github.com/spiritpaper/homebrew-tap-cg    as Formula/cg.rb
# out/cg.json goes to github.com/spiritpaper/scoop-bucket-cg    as bucket/cg.json
# The release workflow runs this after every tag (when the TAP_TOKEN secret is set).
set -eu

tag="$1"
sums="$2"
out="$3"
version="${tag#v}"
repo="spiritpaper/cursed-git"
base="https://github.com/$repo/releases/download/$tag"
mkdir -p "$out"

sum() { # sum <file name>: its sha256 from checksums.txt
  s=$(grep " $1\$" "$sums" | cut -d' ' -f1)
  [ -n "$s" ] || { echo "no checksum for $1" >&2; exit 1; }
  printf '%s' "$s"
}

cat > "$out/cg.rb" <<EOF
# Generated by tools/package-managers.sh for $tag. Don't edit by hand.
class Cg < Formula
  desc "Like git, but she has feelings: a git-learning game you play on a real project"
  homepage "https://github.com/$repo"
  version "$version"
  license "MIT"

  on_macos do
    on_arm do
      url "$base/cg-$tag-darwin-arm64.tar.gz"
      sha256 "$(sum "cg-$tag-darwin-arm64.tar.gz")"
    end
    on_intel do
      url "$base/cg-$tag-darwin-amd64.tar.gz"
      sha256 "$(sum "cg-$tag-darwin-amd64.tar.gz")"
    end
  end
  on_linux do
    on_arm do
      url "$base/cg-$tag-linux-arm64.tar.gz"
      sha256 "$(sum "cg-$tag-linux-arm64.tar.gz")"
    end
    on_intel do
      url "$base/cg-$tag-linux-amd64.tar.gz"
      sha256 "$(sum "cg-$tag-linux-amd64.tar.gz")"
    end
  end

  depends_on "git"

  def install
    bin.install "cg"
  end

  def caveats
    <<~EOS
      Start a game in any git repository:
        cg init                    (Miranda)
        cg init --preset gentle    (Juniper)
    EOS
  end

  test do
    assert_match "cg version", shell_output("#{bin}/cg version")
  end
end
EOF

cat > "$out/cg.json" <<EOF
{
    "version": "$version",
    "description": "Like git, but she has feelings: a git-learning game you play on a real project",
    "homepage": "https://github.com/$repo",
    "license": "MIT",
    "depends": "git",
    "architecture": {
        "64bit": {
            "url": "$base/cg-$tag-windows-amd64.zip",
            "hash": "$(sum "cg-$tag-windows-amd64.zip")",
            "extract_dir": "cg-$tag-windows-amd64"
        },
        "arm64": {
            "url": "$base/cg-$tag-windows-arm64.zip",
            "hash": "$(sum "cg-$tag-windows-arm64.zip")",
            "extract_dir": "cg-$tag-windows-arm64"
        }
    },
    "bin": "cg.exe",
    "notes": "Start a game in any git repository: cg init (Miranda) or cg init --preset gentle (Juniper). She plays in Windows Terminal, PowerShell and cmd.",
    "checkver": "github",
    "autoupdate": {
        "architecture": {
            "64bit": {
                "url": "https://github.com/$repo/releases/download/v\$version/cg-v\$version-windows-amd64.zip",
                "extract_dir": "cg-v\$version-windows-amd64"
            },
            "arm64": {
                "url": "https://github.com/$repo/releases/download/v\$version/cg-v\$version-windows-arm64.zip",
                "extract_dir": "cg-v\$version-windows-arm64"
            }
        }
    }
}
EOF
echo "wrote $out/cg.rb and $out/cg.json for $tag"
